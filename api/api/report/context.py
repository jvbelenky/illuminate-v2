def _finite(v) -> Optional[float]:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return f if math.isfinite(f) else None


def _stats(zone) -> Stats:
    values = zone.get_values() if zone is not None else None
    if values is None:
        return Stats(None, None, None)
    arr = np.asarray(values, dtype=float)
    arr = arr[np.isfinite(arr)]
    if arr.size == 0:
        return Stats(None, None, None)
    return Stats(float(arr.mean()), float(arr.max()), float(arr.min()))


def _is_feet(room) -> bool:
    return "feet" in str(room.dim.units).lower() or "ft" == str(room.dim.units).lower()


def _units(room) -> Units:
    return Units("ft", "ft²", "ft³") if _is_feet(room) else Units("m", "m²", "m³")


def _page_size(room, options: ReportOptions) -> str:
    if options.page_size == "a4":
        return "A4"
    if options.page_size == "letter":
        return "Letter"
    return "Letter" if _is_feet(room) else "A4"


def _exposure_label(zone) -> Optional[str]:
    if not zone.dose:
        return None
    secs = zone.exposure_time.total_seconds()
    hours = secs / 3600
    if hours >= 1 and abs(hours - round(hours)) < 1e-9:
        return f"{int(round(hours))} h dose"
    if secs >= 60 and abs(secs / 60 - round(secs / 60)) < 1e-9:
        return f"{int(round(secs / 60))} min dose"
    return f"{secs:g} s dose"


def _zone_units(zone) -> str:
    return "mJ/cm²" if zone.dose else "µW/cm²"


def _fixture_name(lamp, given: str | None = None) -> str:
    """Preset display name. For a custom fixture, in order: the model name the
    browser sent (its custom-lamp definition or IES filename), the user's own
    lamp name, the IES file's [LUMINAIRE] keyword, the photometric file's name,
    else "Custom fixture"."""
    preset = getattr(lamp, "preset_id", None)
    if preset and preset != "custom":
        return LAMP_DISPLAY_NAMES.get(str(preset), str(preset).replace("_", " ").title())
    if given and given.strip():
        return given.strip()
    name = str(getattr(lamp, "name", "") or "").strip()
    if name and not _AUTO_LAMP_NAME.match(name):
        return name
    # lamp.keywords is guv_calcs's preset list; the IES header's own keywords sit on lamp.ies
    keywords = getattr(getattr(getattr(lamp, "ies", None), "header", None), "keywords", None)
    luminaire = str(keywords.get("LUMINAIRE") or "").strip() if isinstance(keywords, dict) else ""
    if luminaire and luminaire.lower() not in _PLACEHOLDER_KEYWORDS:
        return luminaire
    filedata = getattr(lamp, "filedata", None)
    if isinstance(filedata, (str, Path)) and str(filedata):
        return Path(str(filedata)).name
    return "Custom fixture"


def _type_label(lamp) -> str:
    """The lamp's kind for a reader: 222 nm, 254 nm, or a custom wavelength
    (user-specified, or the peak of the uploaded spectrum)."""
    guv = str(getattr(getattr(lamp, "guv_type", None), "value", "") or "").lower()
    if guv == "krcl":
        return "222 nm"
    if guv == "lphg":
        return "254 nm"
    wavelength = _finite(getattr(lamp, "wavelength", None))
    spectrum = getattr(lamp, "spectrum", None)
    if wavelength is None and spectrum is not None:
        wavelength = _finite(getattr(spectrum, "peak_wavelength", None))
    if wavelength is None:
        return "Custom wavelength"
    return f"Custom wavelength ({wavelength:g} nm)"


def _dimming_note(skin_dim: float, eye_dim: float) -> Optional[str]:
    d = min(skin_dim, eye_dim)
    if d >= 1:
        return None
    minimum = math.floor(d * 100)
    suggested = max(math.floor(d * 0.9 * 100), 0)
    if suggested >= minimum:
        suggested = minimum - 1
    return f"Dim to {suggested}% (minimum {minimum}%)"


def _occupancy(hours: dict[str, HoursToLimit], standard_label: str) -> Occupancy:
    uses_icnirp = "ICNIRP" in standard_label
    h = hours["ICNIRP" if uses_icnirp else "ACGIH"]
    candidates = [v for v in (h.skin, h.eye) if v is not None]
    headline = min(candidates) if candidates else None
    name = "ICNIRP limit" if uses_icnirp else "ACGIH TLV"
    if headline is None:
        return Occupancy(None, name, False, "Occupancy limit could not be evaluated")
    if headline >= 8:
        return Occupancy(headline, name, True, f"Continuous occupancy is within the {name}")
    return Occupancy(headline, name, False, f"Safe to occupy for {headline:.1f} hours per day ({name})")


def _dose_to_irradiance(s: Stats) -> Stats:
    """8 h dose (mJ/cm²) → irradiance (µW/cm²)."""
    def f(v):
        return None if v is None else v * 1000 / (8 * 3600)
    return Stats(f(s.mean), f(s.max), f(s.min))


