def _room_info(room) -> RoomInfo:
    d = room.dim
    poly = d.polygon
    vertices = getattr(poly, "vertices", None)
    return RoomInfo(
        name=room.name, x=float(d.x), y=float(d.y), z=float(d.z),
        floor_area=float(poly.area), volume=float(room.volume),
        shape="polygon" if d.is_polygon else "rectangle",
        vertex_count=len(vertices) if vertices is not None else 4,
        air_changes=float(room.air_changes),
        reflectance_enabled=bool(room.ref_manager.enabled),
    )


def _surfaces(room) -> list[SurfaceRow]:
    return [SurfaceRow(k.replace("_", " ").title(), float(v.R)) for k, v in room.surfaces.items()]


def _lamps(room, fixture_names: dict[str, str]) -> list[LampRow]:
    return [
        LampRow(
            lamp_id=str(lid), name=lamp.name, fixture=_fixture_name(lamp, fixture_names.get(str(lid))),
            type_label=_type_label(lamp),
            wavelength=_finite(lamp.wavelength), output_percent=float(lamp.scaling_factor) * 100,
            position=(float(lamp.x), float(lamp.y), float(lamp.z)),
            aim=(float(lamp.aimx), float(lamp.aimy), float(lamp.aimz)),
            heading=float(lamp.heading), bank=float(lamp.bank), enabled=bool(lamp.enabled),
        )
        for lid, lamp in room.lamps.items()
    ]


def _objects(room) -> list[ObjectRow]:
    rows = []
    for obj in getattr(room, "objects", {}).values():
        data = obj.to_dict()
        rows.append(ObjectRow(
            name=obj.name, size=(float(obj.width), float(obj.length), float(obj.height)),
            base_centre=(float(obj.x), float(obj.y), float(obj.z)), yaw=float(data.get("yaw", 0.0) or 0.0),
            reflectance=float(obj.R), transmittance=float(obj.T), enabled=bool(obj.enabled),
        ))
    return rows


def _as_dict(value, species: list[str]) -> dict:
    """room.average_value returns a float for one species and a dict for a list."""
    if isinstance(value, dict):
        return value
    return {species[0]: value} if len(species) == 1 else {}


def _pathogens(room, species: list[str]) -> tuple[list[PathogenRow], FluenceInfo, Any]:
    """Pathogen rows, fluence info, and the InactivationData they came from."""
    wrf = room.calc_zones.get(WHOLE_ROOM_FLUENCE)
    stats = _stats(wrf)
    fluence_dict = wrf.calculator.cache.by_wavelength(room.lamps, reduce=np.mean) if wrf is not None else {}
    data = room.get_efficacy_data(WHOLE_ROOM_FLUENCE)
    base = data.base_df
    available = {int(w) for w in base["wavelength [nm]"].unique()}
    used = sorted(int(w) for w in fluence_dict if int(w) in available)
    missing = sorted(int(w) for w in fluence_dict if int(w) not in available)
    rows: list[PathogenRow] = []
    if species and not used:
        raise ReportDataError(f"No inactivation data for '{species[0]}' at the lamps' wavelengths")
    if used and species:
        # Validate up front: guv_calcs raises an unnamed "No data available for
        # wavelength" error when any requested species lacks a wavelength.
        wavelengths_of = base.groupby("Species")["wavelength [nm]"].apply(lambda s: {int(w) for w in s}).to_dict()
        for sp in species:
            if not set(used) <= wavelengths_of.get(sp, set()):
                raise ReportDataError(f"No inactivation data for '{sp}' at the lamps' wavelengths")
        # room.average_value would build a fresh InactivationData per call; the
        # one above already holds the computed columns for every species
        values = {
            fn: _as_dict(data.average_value(function=fn, species=species), species)
            for fn in EFFICACY_FUNCTIONS
        }
        cats = base.drop_duplicates("Species").set_index("Species")["Category"].to_dict()
        for sp in species:
            each = _finite(values["each_uv"].get(sp))
            if each is None:
                raise ReportDataError(f"No inactivation data for '{sp}' at the lamps' wavelengths")
            rows.append(PathogenRow(
                species=sp, category=str(cats.get(sp, "")), each_uv=each,
                cadr_lps=_finite(values["cadr_lps"].get(sp)) or 0.0,
                cadr_cfm=_finite(values["cadr_cfm"].get(sp)) or 0.0,
                t90=_finite(values["log1"].get(sp)), t99=_finite(values["log2"].get(sp)),
                t999=_finite(values["log3"].get(sp)),
            ))
    return rows, FluenceInfo(stats=stats, wavelengths_used=used, wavelengths_missing=missing,
                             image_key=f"volume:{WHOLE_ROOM_FLUENCE}", levels=report_iso_levels(stats.mean),
                             by_wavelength={int(w): float(v) for w, v in fluence_dict.items()}), data


def _safety(room) -> SafetyInfo:
    skin = room.calc_zones.get(SKIN_LIMITS)
    eye = room.calc_zones.get(EYE_LIMITS)
    label = _standard_to_label(room.standard)
    hours = hours_to_limit_by_standard(room)
    result = room.check_lamps()
    lamps = [
        LampSafetyRow(
            name=r.lamp_name, skin_dose=float(r.skin_dose_max), skin_tlv=float(r.skin_tlv),
            eye_dose=float(r.eye_dose_max), eye_tlv=float(r.eye_tlv),
            compliant=bool(r.is_skin_compliant and r.is_eye_compliant),
            dimming_note=_dimming_note(r.skin_dimming_required, r.eye_dimming_required),
            missing_spectrum=bool(r.missing_spectrum),
        )
        for r in result.lamp_results.values()
    ]
    warnings = [w.message for w in result.warnings if not w.lamp_id]
    skin_stats, eye_stats = _stats(skin), _stats(eye)
    has_222 = any(_finite(l.wavelength) == 222 for l in room.lamps.values())
    ozone = _finite(room.estimate_ozone_increase()) if has_222 else None
    return SafetyInfo(
        standard_label=label, hours=hours, skin=skin_stats, eye=eye_stats,
        skin_irradiance=_dose_to_irradiance(skin_stats), eye_irradiance=_dose_to_irradiance(eye_stats),
        lamps=lamps, warnings=warnings, occupancy=_occupancy(hours, label),
        has_222nm=has_222, air_changes=float(room.air_changes),
        ozone_decay_constant=_finite(getattr(room, "ozone_decay_constant", None)), ozone_ppb=ozone,
    )


def _point_position(zone) -> tuple[float, float, float]:
    g = zone.geometry
    for attr in ("position", "point"):
        p = getattr(g, attr, None)
        if p is not None:
            arr = np.ravel(np.asarray(p, dtype=float))
            if arr.size >= 3:
                return (float(arr[0]), float(arr[1]), float(arr[2]))
    if all(hasattr(g, a) for a in ("x", "y", "z")):
        return (float(np.ravel(g.x)[0]), float(np.ravel(g.y)[0]), float(np.ravel(g.z)[0]))
    pts = np.asarray(getattr(g, "points", np.zeros(3)), dtype=float).reshape(-1, 3)
    return (float(pts[0][0]), float(pts[0][1]), float(pts[0][2]))


def _custom_zones(room) -> tuple[list[PlaneZone], list[VolumeZone], list[PointZone]]:
    planes, vols, pts = [], [], []
    for zid, z in room.calc_zones.items():
        if zid in STANDARD_IDS or z.get_values() is None:
            continue
        ct = z.calctype.lower()
        if ct == "plane":
            planes.append(PlaneZone(zid, z.name, _finite(getattr(z.geometry, "height", None)),
                                    _zone_units(z), _exposure_label(z), _stats(z)))
        elif ct == "volume":
            vols.append(VolumeZone(zid, z.name, _zone_units(z), _exposure_label(z), _stats(z), f"volume:{zid}"))
        else:
            pts.append(PointZone(zid, z.name, _point_position(z), _zone_units(z),
                                 _finite(np.ravel(z.get_values())[0])))
    return planes, vols, pts


def _lamp_types(room, fixture_names: dict[str, str]) -> list[LampTypeInfo]:
    seen: dict[str, LampTypeInfo] = {}
    for lid, lamp in room.lamps.items():
        fx = _fixture_name(lamp, fixture_names.get(str(lid)))
        if fx not in seen:
            seen[fx] = LampTypeInfo(fx, _finite(lamp.wavelength), str(lid), lamp.spectrum is not None)
    return list(seen.values())


def build_report_context(room, request: ReportRequest, images: dict[str, bytes], versions: Versions) -> ReportContext:
    pathogens, fluence, efficacy_data = _pathogens(room, list(request.pathogens))
    lead = pathogens[0] if pathogens else None
    planes, vols, pts = _custom_zones(room)
    return ReportContext(
        meta=request.meta, options=request.options, generated_at=datetime.now(), versions=versions,
        page_size=_page_size(room, request.options), units=_units(room),
        precision=max(int(getattr(room, "precision", 1) or 1), 1), images=images,
        room=_room_info(room), surfaces=_surfaces(room), lamps=_lamps(room, request.fixture_names), objects=_objects(room),
        summary=Summary(
            each_uv=lead.each_uv if lead else None, cadr_lps=lead.cadr_lps if lead else None,
            cadr_cfm=lead.cadr_cfm if lead else None, avg_fluence=fluence.stats.mean,
            lead_species=lead.species if lead else None,
        ),
        safety=_safety(room), pathogens=pathogens, fluence=fluence,
        custom_planes=planes, custom_volumes=vols, custom_points=pts, lamp_types=_lamp_types(room, request.fixture_names),
        efficacy_data=efficacy_data,
    )
