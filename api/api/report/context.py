class ObjectRow:
    name: str
    size: tuple[float, float, float]
    base_centre: tuple[float, float, float]
    yaw: float
    reflectance: float
    transmittance: float
    enabled: bool


@dataclass(frozen=True)
class PathogenRow:
    species: str
    category: str
    each_uv: float
    cadr_lps: float
    cadr_cfm: float
    t90: Optional[float]
    t99: Optional[float]
    t999: Optional[float]


@dataclass(frozen=True)
class LampSafetyRow:
    name: str
    skin_dose: float
    skin_tlv: float
    eye_dose: float
    eye_tlv: float
    compliant: bool
    dimming_note: Optional[str]   # "Dim to 71% (minimum 79%)" or None
    missing_spectrum: bool


@dataclass(frozen=True)
class Occupancy:
    headline_hours: Optional[float]
    headline_name: str            # "ACGIH TLV" | "ICNIRP limit"
    unlimited: bool
    statement: str


@dataclass(frozen=True)
class SafetyInfo:
    standard_label: str
    hours: dict[str, HoursToLimit]
    skin: Stats
    eye: Stats
    skin_irradiance: Stats        # µW/cm² behind the 8 h doses
    eye_irradiance: Stats
    lamps: list[LampSafetyRow]
    warnings: list[str]
    occupancy: Occupancy
    has_222nm: bool               # ozone is only generated by 222 nm sources
    air_changes: float            # ventilation, per hour
    ozone_decay_constant: Optional[float]
    ozone_ppb: Optional[float]    # None without 222 nm sources


@dataclass(frozen=True)
class Summary:
    each_uv: Optional[float]
    cadr_lps: Optional[float]
    cadr_cfm: Optional[float]
    avg_fluence: Optional[float]
    lead_species: Optional[str]


@dataclass(frozen=True)
class FluenceInfo:
    stats: Stats
    wavelengths_used: list[int]
    wavelengths_missing: list[int]
    image_key: str
    levels: list[float]           # isosurface levels drawn in the capture (see report_iso_levels)
    by_wavelength: dict[int, float]  # average fluence per lamp wavelength (µW/cm²)


def report_iso_levels(mean: Optional[float]) -> list[float]:
    """Isosurface levels the frontend draws for a report capture: half, once and
    twice the zone's average, each to two significant figures. Mirrors
    `reportIsoLevels` in ui/src/lib/utils/reportCapture.ts."""
    if mean is None or not math.isfinite(mean) or mean <= 0:
        return []
    levels = []
    for k in (0.5, 1.0, 2.0):
        # Two significant figures, rounding halves up like JavaScript's toPrecision
        d = Decimal(str(mean * k))
        quantum = Decimal(1).scaleb(d.adjusted() - 1)
        levels.append(float(d.quantize(quantum, rounding=ROUND_HALF_UP)))
    return levels


