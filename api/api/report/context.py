    name: str
    fixture: str
    type_label: str               # "222 nm" | "254 nm" | "Custom wavelength (265 nm)"
    wavelength: Optional[float]
    output_percent: float
    position: tuple[float, float, float]
    aim: tuple[float, float, float]
    heading: float
    bank: float
    enabled: bool


